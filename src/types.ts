// ─── Buffers ────────────────────────────────────────────────────────────────

export type BufferItemStatus = "pending" | "running" | "completed" | "failed";

export interface Buffer {
  id: string;
  name: string;
  url: string;
  method: string;
  timeout_seconds: number;
  rate_limit: number;
  max_retries: number;
  backoff: Backoff;
  paused: boolean;
  webhook_url?: string | null;
  created_at: string;
  updated_at: string;
}

export interface BufferItem {
  id: string;
  buffer_id: string;
  status: BufferItemStatus;
  status_code: number | null;
  retry_count: number;
  max_retries: number;
  last_error: string | null;
  /** Set when this item was created by replaying a failed one — the source item id. */
  replay_of?: string | null;
  created_at: string;
  completed_at: string | null;
}

/** Per-buffer item status breakdown — server-aggregated (not page-limited). */
export interface BufferStats {
  pending: number;
  running: number;
  completed: number;
  failed: number;
  total: number;
  /** completed / (completed + failed), in [0,1]; 0 when none have finished. */
  success_rate: number;
}

export interface CreateBufferInput {
  name: string;
  url: string;
  method?: string;
  headers?: Record<string, string>;
  timeout_seconds?: number;
  rate_limit: number;
  max_retries?: number;
  backoff?: Backoff;
  webhook_url?: string;
  webhook_headers?: Record<string, string>;
}

export interface PushBufferItemInput {
  body?: string;
  headers?: Record<string, string>;
  /** Auto-generated by the SDK when omitted, so retries are safe by default. */
  idempotency_key?: string;
}

export interface ListBuffersParams {
  cursor?: string;
  limit?: number;
}

export interface ListBufferItemsParams {
  cursor?: string;
  limit?: number;
  status?: BufferItemStatus;
}

export interface BufferPage {
  buffers: Buffer[];
  next_cursor: string | null;
}

export interface BufferItemPage {
  items: BufferItem[];
  next_cursor: string | null;
}

