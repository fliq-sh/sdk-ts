// Resource types for the Fliq API. These mirror the request/response shapes of
// the Go core-api (see fliq-sh/core-api) and the dashboard client.

// ─── Jobs ───────────────────────────────────────────────────────────────────

export type JobStatus =
  | "pending"
  | "running"
  | "completed"
  | "failed"
  | "cancelled";

export type Backoff = "exponential" | "linear";

export interface Job {
  id: string;
  user_id: string;
  url: string;
  method: string;
  headers: Record<string, string> | null;
  body: string | null;
  status: JobStatus;
  scheduled_at: string;
  started_at: string | null;
  completed_at: string | null;
  attempts: number;
  max_retries: number;
  timeout_seconds: number;
  idempotency_key: string | null;
  webhook_url?: string | null;
  webhook_headers?: Record<string, string> | null;
  /** Set when this job was created by replaying a failed one — the source job id. */
  replay_of?: string | null;
  created_at: string;
  updated_at: string;
}

export interface JobAttempt {
  id: string;
  job_id: string;
  attempt_num: number;
  worker_id: string;
  started_at: string;
  completed_at: string | null;
  status_code: number | null;
  error: string | null;
}

export interface CreateJobInput {
  url: string;
  method: string;
  headers?: Record<string, string>;
  body?: string;
  scheduled_at: string;
  max_retries?: number;
  timeout_seconds?: number;
  /** Auto-generated by the SDK when omitted, so retries are safe by default. */
  idempotency_key?: string;
  backoff?: Backoff;
  webhook_url?: string;
  webhook_headers?: Record<string, string>;
}

export interface CreateJobResponse {
  id: string;
  created_at: string;
}

export interface ReplayJobResponse {
  id: string;
  status: JobStatus;
  replay_of?: string | null;
  scheduled_at: string;
  created_at: string;
}

export interface ListJobsParams {
  cursor?: string;
  limit?: number;
  status?: JobStatus;
}

export interface JobPage {
  jobs: Job[];
  next_cursor: string | null;
}

